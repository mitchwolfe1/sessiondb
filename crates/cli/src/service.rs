//! User-login service management. Credentials are resolved by the worker at runtime.
use anyhow::{Context, Result, bail, ensure};
use directories::BaseDirs;
use serde::Serialize;
use sha2::{Digest, Sha256};
use std::{
    fs::{self, File, OpenOptions},
    io::{ErrorKind, Write},
    path::{Path, PathBuf},
    process::{Command, Output},
};

const MARK: &str = "Generated by sessiondb sync install";

#[derive(Clone, Copy, PartialEq, Eq)]
enum Manager {
    Systemd,
    Launchd,
}

pub struct Service {
    manager: Manager,
    name: String,
    definition: PathBuf,
    directory: PathBuf,
}

#[derive(Serialize)]
pub struct ServiceStatus {
    pub manager: &'static str,
    pub name: String,
    pub installed: bool,
    pub enabled_at_login: Option<bool>,
    pub state: String,
    pub definition: PathBuf,
}

enum Definition {
    Missing,
    Managed(String),
    External,
}

struct NativeState {
    state: String,
    enabled: bool,
    loaded: bool,
}

fn utf8(path: &Path) -> Result<&str> {
    path.to_str().context("service paths must be valid UTF-8")
}

fn unit_arg(s: &str) -> String {
    let mut quoted = String::from("\"");
    for c in s.chars() {
        match c {
            '\\' => quoted.push_str("\\\\"),
            '"' => quoted.push_str("\\\""),
            '%' => quoted.push_str("%%"),
            '\n' => quoted.push_str("\\n"),
            '\r' => quoted.push_str("\\r"),
            '\t' => quoted.push_str("\\t"),
            c if c.is_control() => quoted.push_str(&format!("\\u{:04x}", c as u32)),
            c => quoted.push(c),
        }
    }
    quoted.push('"');
    quoted
}

fn xml(s: &str) -> Result<String> {
    ensure!(
        s.chars()
            .all(|c| matches!(c, '\t' | '\n' | '\r')
                || (c >= ' ' && c != '\u{fffe}' && c != '\u{ffff}')),
        "service argument cannot be represented in a launchd property list"
    );
    Ok(s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('\r', "&#13;"))
}

fn checked(mut cmd: Command) -> Result<()> {
    let program = cmd.get_program().to_owned();
    let out = cmd
        .output()
        .with_context(|| format!("run {}", program.to_string_lossy()))?;
    if !out.status.success() {
        bail!(
            "{} exited with {}: {}",
            program.to_string_lossy(),
            out.status,
            String::from_utf8_lossy(&out.stderr).trim()
        );
    }
    Ok(())
}

fn command(program: &str, args: &[&str]) -> Command {
    let mut cmd = Command::new(program);
    cmd.args(args);
    cmd
}

impl Service {
    pub fn current(directory: &Path) -> Result<Option<Self>> {
        let manager = if cfg!(target_os = "linux") {
            Manager::Systemd
        } else if cfg!(target_os = "macos") {
            Manager::Launchd
        } else {
            return Ok(None);
        };
        let dirs = BaseDirs::new().context("user home directory is unavailable")?;
        let default = match manager {
            Manager::Systemd => dirs.home_dir().join(".local/state/sessiondb"),
            Manager::Launchd => dirs.data_local_dir().join("sessiondb"),
        };
        let default = default.canonicalize().unwrap_or(default);
        let suffix = if directory == default {
            String::new()
        } else {
            format!(
                "-{}",
                &hex::encode(Sha256::digest(utf8(directory)?.as_bytes()))[..16]
            )
        };
        let (name, definition) = match manager {
            Manager::Systemd => {
                let name = format!("sessiondb-sync{suffix}.service");
                let file = dirs.config_dir().join("systemd/user").join(&name);
                (name, file)
            }
            Manager::Launchd => {
                let name = format!("io.sessiondb.sync{suffix}");
                let file = dirs
                    .home_dir()
                    .join("Library/LaunchAgents")
                    .join(format!("{name}.plist"));
                (name, file)
            }
        };
        Ok(Some(Self {
            manager,
            name,
            definition,
            directory: directory.to_owned(),
        }))
    }

    pub fn lock(&self) -> Result<File> {
        let file = OpenOptions::new()
            .write(true)
            .create(true)
            .truncate(false)
            .open(self.directory.join("service.lock"))?;
        file.try_lock()
            .context("another sync service command is in progress")?;
        Ok(file)
    }

    fn registration(&self) -> Result<Definition> {
        let meta = match fs::symlink_metadata(&self.definition) {
            Ok(meta) => meta,
            Err(e) if e.kind() == ErrorKind::NotFound => return Ok(Definition::Missing),
            Err(e) => return Err(e.into()),
        };
        if meta.is_file() {
            let data = fs::read(&self.definition)?;
            if let Ok(text) = String::from_utf8(data) {
                let marker = match self.manager {
                    Manager::Systemd => format!("# {MARK}"),
                    Manager::Launchd => format!("<!-- {MARK} -->"),
                };
                if text.lines().take(2).any(|line| line == marker) {
                    return Ok(Definition::Managed(text));
                }
            }
        }
        Ok(Definition::External)
    }

    fn owned(&self) -> Result<Option<String>> {
        match self.registration()? {
            Definition::Missing => Ok(None),
            Definition::Managed(text) => Ok(Some(text)),
            Definition::External => bail!(
                "service definition is managed externally: {}",
                self.definition.display()
            ),
        }
    }

    fn definition(&self, args: &[String], cwd: Option<&Path>) -> Result<String> {
        match self.manager {
            Manager::Systemd => {
                // The ':' command prefix makes dollar signs literal. Specifiers still need escaping.
                let mut words = vec![unit_arg(&format!(":{}", args[0]))];
                words.extend(args[1..].iter().map(|s| unit_arg(s)));
                let mut body = format!(
                    "# {MARK}\n[Unit]\nDescription=SessionDB background sync\n\n[Service]\nType=exec\nExecStart={}\n",
                    words.join(" ")
                );
                if let Some(cwd) = cwd {
                    let cwd = utf8(cwd)?;
                    ensure!(
                        !cwd.contains(['\n', '\r']),
                        "working directory contains a line break"
                    );
                    body.push_str(&format!("WorkingDirectory={}/.\n", cwd.replace('%', "%%")));
                }
                body.push_str("Restart=on-failure\nRestartSec=30\nKillSignal=SIGINT\nSuccessExitStatus=130\n\n[Install]\nWantedBy=default.target\n");
                Ok(body)
            }
            Manager::Launchd => {
                let mut body = format!(
                    "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- {MARK} -->\n<plist version=\"1.0\"><dict>\n<key>Label</key><string>{}</string>\n<key>ProgramArguments</key><array>\n",
                    xml(&self.name)?
                );
                for arg in args {
                    body.push_str(&format!("<string>{}</string>\n", xml(arg)?));
                }
                body.push_str("</array>\n<key>RunAtLoad</key><true/>\n<key>KeepAlive</key><dict><key>SuccessfulExit</key><false/></dict>\n<key>ThrottleInterval</key><integer>30</integer>\n");
                if let Some(cwd) = cwd {
                    body.push_str(&format!(
                        "<key>WorkingDirectory</key><string>{}</string>\n",
                        xml(utf8(cwd)?)?
                    ));
                }
                let log = xml(utf8(&self.directory.join("sync.log"))?)?;
                body.push_str(&format!("<key>StandardOutPath</key><string>{log}</string>\n<key>StandardErrorPath</key><string>{log}</string>\n</dict></plist>\n"));
                Ok(body)
            }
        }
    }

    fn systemctl(&self, args: &[&str]) -> Command {
        let mut cmd = command("systemctl", &["--user"]);
        cmd.args(args);
        cmd
    }

    fn domain(&self) -> Result<String> {
        let out = command("id", &["-u"])
            .output()
            .context("get login user ID")?;
        ensure!(out.status.success(), "could not get login user ID");
        let uid = std::str::from_utf8(&out.stdout)?.trim().parse::<u32>()?;
        Ok(format!("gui/{uid}"))
    }

    // A missing job is expected before bootstrap and after bootout. Other manager errors matter.
    fn launch_state(&self, target: &str) -> Result<Option<String>> {
        let Output {
            status,
            stdout,
            stderr,
        } = command("launchctl", &["print", target])
            .output()
            .context("run launchctl")?;
        if !status.success() {
            let err = String::from_utf8_lossy(&stderr);
            if status.code() == Some(113) || err.contains("Could not find service") {
                return Ok(None);
            }
            bail!("launchctl print: {}", err.trim());
        }
        let state = String::from_utf8_lossy(&stdout)
            .lines()
            .find_map(|l| l.trim().strip_prefix("state = "))
            .unwrap_or("loaded")
            .to_owned();
        Ok(Some(state))
    }

    fn native_state(&self) -> Result<NativeState> {
        match self.manager {
            Manager::Systemd => {
                let out = self
                    .systemctl(&[
                        "show",
                        "--property=LoadState,ActiveState,UnitFileState",
                        &self.name,
                    ])
                    .output()
                    .context("run systemctl --user")?;
                let fields = String::from_utf8(out.stdout)?;
                let field = |field: &str| fields.lines().find_map(|line| line.strip_prefix(field));
                let loaded = field("LoadState=") != Some("not-found");
                ensure!(
                    out.status.success() || !loaded,
                    "systemctl --user show: {}",
                    String::from_utf8_lossy(&out.stderr).trim()
                );
                let state = match field("ActiveState=").context("missing systemd service state")? {
                    "active" => "running",
                    "inactive" => "stopped",
                    other => other,
                }
                .to_owned();
                Ok(NativeState {
                    state,
                    loaded,
                    enabled: field("UnitFileState=") == Some("enabled"),
                })
            }
            Manager::Launchd => {
                let domain = self.domain()?;
                let overrides = command("launchctl", &["print-disabled", &domain])
                    .output()
                    .context("run launchctl print-disabled")?;
                ensure!(
                    overrides.status.success(),
                    "launchctl print-disabled: {}",
                    String::from_utf8_lossy(&overrides.stderr).trim()
                );
                let disabled = String::from_utf8_lossy(&overrides.stdout)
                    .lines()
                    .filter_map(|l| l.split_once("=>"))
                    .any(|(label, value)| {
                        label.trim().trim_matches('"') == self.name
                            && matches!(value.trim(), "disabled" | "true")
                    });
                let native = self.launch_state(&format!("{domain}/{}", self.name))?;
                Ok(NativeState {
                    loaded: native.is_some(),
                    state: native.unwrap_or_else(|| "stopped".into()),
                    enabled: !disabled,
                })
            }
        }
    }

    pub fn status(&self) -> Result<ServiceStatus> {
        let (installed, state, enabled) = match self.registration()? {
            Definition::Missing => (false, "uninstalled".into(), Some(false)),
            Definition::External => (true, "externally managed".into(), None),
            Definition::Managed(_) => match self.native_state() {
                Ok(native) => (true, native.state, Some(native.enabled)),
                Err(_) => (true, "unavailable".into(), None),
            },
        };
        Ok(ServiceStatus {
            manager: if self.manager == Manager::Systemd {
                "systemd"
            } else {
                "launchd"
            },
            name: self.name.clone(),
            installed,
            state,
            enabled_at_login: enabled,
            definition: self.definition.clone(),
        })
    }

    fn write_definition(&self, contents: &str, existing: bool) -> Result<()> {
        let parent = self
            .definition
            .parent()
            .context("missing service definition directory")?;
        fs::create_dir_all(parent)?;
        let mut tmp = tempfile::NamedTempFile::new_in(parent)?;
        tmp.write_all(contents.as_bytes())?;
        tmp.as_file().sync_all()?;
        if existing {
            tmp.persist(&self.definition)
        } else {
            tmp.persist_noclobber(&self.definition)
        }
        .map_err(|e| e.error)?;
        Ok(())
    }

    fn configure(&self, enabled: bool, running: bool) -> Result<()> {
        match self.manager {
            Manager::Systemd => {
                if enabled {
                    checked(self.systemctl(&["enable", utf8(&self.definition)?]))?;
                } else {
                    checked(self.systemctl(&["disable", &self.name]))?;
                }
                checked(self.systemctl(&["daemon-reload"]))?;
                checked(self.systemctl(&[if running { "restart" } else { "stop" }, &self.name]))
            }
            Manager::Launchd => {
                let domain = self.domain()?;
                let target = format!("{domain}/{}", self.name);
                if self.launch_state(&target)?.is_some() {
                    checked(command("launchctl", &["bootout", &target]))?;
                }
                checked(command(
                    "launchctl",
                    &[if enabled { "enable" } else { "disable" }, &target],
                ))?;
                if running {
                    checked(command(
                        "launchctl",
                        &["bootstrap", &domain, utf8(&self.definition)?],
                    ))?;
                }
                Ok(())
            }
        }
    }

    pub fn install(&self, args: &[String], cwd: Option<&Path>) -> Result<()> {
        let previous = self.owned()?;
        let prior = self.native_state()?;
        ensure!(
            previous.is_some() || !prior.loaded,
            "service name {} is already in use by the login manager",
            self.name
        );
        let contents = self.definition(args, cwd)?;
        self.write_definition(&contents, previous.is_some())?;
        if let Err(error) = self.configure(true, true) {
            let rollback = if let Some(old) = previous {
                let running = prior.loaded && !matches!(prior.state.as_str(), "stopped" | "failed");
                self.write_definition(&old, true)
                    .and_then(|()| self.configure(prior.enabled, running))
            } else {
                self.uninstall()
            };
            if let Err(cleanup) = rollback {
                bail!("install failed: {error:#}; service recovery failed: {cleanup:#}");
            }
            return Err(error.context("installing the background service"));
        }
        Ok(())
    }

    pub fn start(&self) -> Result<()> {
        ensure!(
            self.owned()?.is_some(),
            "install the watcher with sessiondb sync install"
        );
        match self.manager {
            Manager::Systemd => checked(self.systemctl(&["start", &self.name])),
            Manager::Launchd => {
                let domain = self.domain()?;
                let target = format!("{domain}/{}", self.name);
                match self.launch_state(&target)? {
                    None => checked(command(
                        "launchctl",
                        &["bootstrap", &domain, utf8(&self.definition)?],
                    )),
                    Some(s) if s == "running" => Ok(()),
                    Some(_) => checked(command("launchctl", &["kickstart", &target])),
                }
            }
        }
    }
    pub fn stop(&self) -> Result<()> {
        if self.owned()?.is_none() {
            return Ok(());
        }
        match self.manager {
            Manager::Systemd => checked(self.systemctl(&["stop", &self.name])),
            Manager::Launchd => {
                let target = format!("{}/{}", self.domain()?, self.name);
                if self.launch_state(&target)?.is_some() {
                    checked(command("launchctl", &["bootout", &target]))?;
                }
                Ok(())
            }
        }
    }
    pub fn uninstall(&self) -> Result<()> {
        if self.owned()?.is_none() {
            return Ok(());
        }
        if self.manager == Manager::Systemd {
            checked(self.systemctl(&["disable", "--now", &self.name]))?;
        } else {
            self.stop()?;
        }
        fs::remove_file(&self.definition)?;
        if self.manager == Manager::Systemd {
            checked(self.systemctl(&["daemon-reload"]))?;
        }
        Ok(())
    }

    pub fn logs(&self, follow: bool) -> Result<()> {
        ensure!(
            self.owned()?.is_some(),
            "install the watcher with sessiondb sync install"
        );
        let mut cmd = match self.manager {
            Manager::Systemd => command(
                "journalctl",
                &["--user", "--unit", &self.name, "--no-pager", "--lines=50"],
            ),
            Manager::Launchd => command("tail", &["-n", "50"]),
        };
        if follow {
            cmd.arg(if self.manager == Manager::Systemd {
                "--follow"
            } else {
                "-F"
            });
        }
        if self.manager == Manager::Launchd {
            cmd.arg(self.directory.join("sync.log"));
        }
        ensure!(
            cmd.status().context("read sync service logs")?.success(),
            "could not read sync service logs"
        );
        Ok(())
    }
}

#[cfg(all(test, unix))]
mod tests {
    use super::*;
    use std::os::unix::fs::PermissionsExt;

    fn agent(root: &Path) -> Service {
        Service {
            manager: Manager::Launchd,
            name: "io.sessiondb.sync.test".into(),
            definition: root.join("LaunchAgents/io.sessiondb.sync.test.plist"),
            directory: root.to_owned(),
        }
    }

    #[test]
    fn renders_literal_arguments_for_each_manager() {
        let dir = tempfile::tempdir().unwrap();
        let special = "--config=$VALUE %n \"quoted\" \\ <&> \nend".to_owned();
        let args = vec!["/bin/true".to_owned(), special];
        let mut service = agent(dir.path());
        let plist = service.definition(&args, None).unwrap();
        assert!(
            plist.contains("<string>--config=$VALUE %n \"quoted\" \\ &lt;&amp;&gt; \nend</string>")
        );
        assert!(plist.contains("<key>RunAtLoad</key><true/>"));
        service.manager = Manager::Systemd;
        let unit = service.definition(&args, None).unwrap();
        assert!(
            unit.contains(
                r#"ExecStart=":/bin/true" "--config=$VALUE %%n \"quoted\" \\ <&> \nend""#
            )
        );
    }

    #[test]
    fn external_definitions_are_reported_and_preserved() {
        let dir = tempfile::tempdir().unwrap();
        let service = agent(dir.path());
        fs::create_dir_all(service.definition.parent().unwrap()).unwrap();
        fs::write(&service.definition, "manual configuration").unwrap();
        assert_eq!(service.status().unwrap().state, "externally managed");
        assert!(service.install(&["/bin/true".into()], None).is_err());
        assert!(service.uninstall().is_err());
        assert_eq!(
            fs::read_to_string(service.definition).unwrap(),
            "manual configuration"
        );
    }

    #[test]
    fn launchctl_lifecycle_restores_a_working_definition_on_failure() {
        // Give the child its own command search path without changing the test runner's environment.
        const TEST_ROOT: &str = "SESSIONDB_TEST_LAUNCHCTL_ROOT";
        if let Some(root) = std::env::var_os(TEST_ROOT) {
            let root = PathBuf::from(root);
            let svc = agent(&root);
            let args = vec!["/bin/true".into(), "--config=test & work".into()];
            fs::write(root.join("fail-next"), "").unwrap();
            assert!(svc.install(&args, None).is_err());
            assert_eq!(svc.status().unwrap().state, "uninstalled");
            svc.install(&args, None).unwrap();
            let original = fs::read(&svc.definition).unwrap();
            assert_eq!(svc.status().unwrap().state, "running");
            fs::write(root.join("fail-next"), "").unwrap();
            assert!(svc.install(&["/bin/false".into()], None).is_err());
            assert_eq!(fs::read(&svc.definition).unwrap(), original);
            assert_eq!(svc.status().unwrap().state, "running");
            svc.stop().unwrap();
            assert_eq!(svc.status().unwrap().state, "stopped");
            svc.start().unwrap();
            svc.start().unwrap();
            assert_eq!(svc.status().unwrap().state, "running");
            svc.uninstall().unwrap();
            svc.uninstall().unwrap();
            assert_eq!(svc.status().unwrap().state, "uninstalled");
            return;
        }
        let tmp = tempfile::tempdir().unwrap();
        let stub = tmp.path().join("launchctl");
        fs::write(&stub,r#"#!/bin/sh
set -eu
cd "$SESSIONDB_TEST_LAUNCHCTL_ROOT"
case "$1" in
  print-disabled) echo "disabled services = {"; echo "}";;
  print) if test -f loaded; then echo 'state = running'; else echo 'Could not find service' >&2; exit 113; fi;;
  enable|disable) test "$2" = "gui/$(id -u)/io.sessiondb.sync.test";;
  bootout) test "$2" = "gui/$(id -u)/io.sessiondb.sync.test"; rm loaded;;
  bootstrap) test "$2" = "gui/$(id -u)"; test -f "$3"; test ! -e loaded
    if command -v python3 >/dev/null; then
      python3 -c 'import plistlib,sys; p=plistlib.load(open(sys.argv[1],"rb")); assert p["Label"]=="io.sessiondb.sync.test" and isinstance(p["ProgramArguments"],list) and p["RunAtLoad"] is True' "$3"
    fi
    if test -e fail-next; then rm fail-next; exit 5; fi
    touch loaded;;
  *) exit 64;;
esac
"#).unwrap();
        fs::set_permissions(stub, fs::Permissions::from_mode(0o700)).unwrap();
        let mut paths = vec![tmp.path().to_owned()];
        paths.extend(std::env::split_paths(
            &std::env::var_os("PATH").unwrap_or_default(),
        ));
        let outcome = Command::new(std::env::current_exe().unwrap())
            .args([
                "--exact",
                "service::tests::launchctl_lifecycle_restores_a_working_definition_on_failure",
            ])
            .env(TEST_ROOT, tmp.path())
            .env("PATH", std::env::join_paths(paths).unwrap())
            .output()
            .unwrap();
        assert!(
            outcome.status.success(),
            "{}{}",
            String::from_utf8_lossy(&outcome.stdout),
            String::from_utf8_lossy(&outcome.stderr)
        );
    }
}
